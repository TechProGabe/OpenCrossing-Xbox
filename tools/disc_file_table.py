#!/usr/bin/env python3
"""Write xbox/src/disc_table.inc: what a good Animal Crossing USA (GAFE01
rev 0) image holds, for the boot-time disc check (xbox/src/xbox_disc_check.c,
docs/architecture.md "Disc check").

  python tools/disc_file_table.py "<GAFE01 rev 0 image.iso>"

Checks files, not the whole image: a scrubbed dump zeroes the junk between
files, a .ciso (tools/gc_trim_ciso.py) drops it, and a rebuilt image
(GCRebuilder) moves the files and the DOL. So offsets, the boot block and
the FST's bytes are not compared: the DOL and each file's name, size and
contents are. Writes hashes, sizes and the disc's file names only: no game
data.
Reads a plain .iso/.gcm (decompress a .ciso or .rvz with Dolphin first).
"""
import hashlib
import pathlib
import struct
import sys
import zlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / 'xbox/src/disc_table.inc'
GAME_ID = b'GAFE01'
# the other releases, so the error screen can name what it was given
OTHERS = [('GAFE01', 1, 'USA Rev 1'), ('GAFP01', 0, 'PAL'), ('GAFU01', 0, 'Australia'),
          ('GAFJ01', 0, 'Japan'), ('GAEJ01', 0, 'Japan e+')]


def be32(b, o):
    return struct.unpack_from('>I', b, o)[0]


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    path = sys.argv[1]
    f = open(path, 'rb')

    def read(off, n):
        f.seek(off)
        b = f.read(n)
        if len(b) != n:
            sys.exit(f'{path}: short read at {off:#x}')
        return b

    hdr = read(0, 0x440)
    if hdr[:6] != GAME_ID or hdr[7] != 0 or be32(hdr, 0x1C) != 0xC2339F3D:
        sys.exit(f'{path}: not GAFE01 rev 0 ({hdr[:6]!r} rev {hdr[7]})')
    dol_off, fst_off, fst_len = be32(hdr, 0x420), be32(hdr, 0x424), be32(hdr, 0x428)
    dolh = read(dol_off, 0x100)
    dol_len = max(be32(dolh, i * 4) + be32(dolh, 0x90 + i * 4) for i in range(18) if be32(dolh, 0x90 + i * 4))
    fst = read(fst_off, fst_len)

    def crc(off, n):
        c = 0
        while n:
            k = min(n, 1 << 22)
            c = zlib.crc32(read(off, k), c)
            off += k
            n -= k
        return c & 0xFFFFFFFF

    n = be32(fst, 8)
    names = n * 12
    files = []
    stack = []
    for i in range(1, n):
        while stack and i >= stack[-1][1]:
            stack.pop()
        word, off, size = struct.unpack_from('>III', fst, i * 12)
        end = fst.index(b'\0', names + (word & 0xFFFFFF))
        name = fst[names + (word & 0xFFFFFF):end].decode('ascii')
        full = (stack[-1][0] if stack else '') + name
        if word >> 24:
            stack.append((full + '/', size))
        else:
            files.append((full, off, size, crc(off, size)))

    print('hashing the image...', file=sys.stderr)
    h = hashlib.sha1()
    f.seek(0)
    for block in iter(lambda: f.read(1 << 22), b''):
        h.update(block)
    size = f.tell()

    lines = [
        '/* disc_table.inc - a good Animal Crossing USA (GAFE01 rev 0) image, for the',
        ' * boot-time disc check (xbox_disc_check.c). Generated by',
        ' * tools/disc_file_table.py; do not edit. Hashes and names only. */',
        f'/* made from a {size}-byte image, SHA-1 {h.hexdigest()} */',
        f'#define DISC_DOL_SIZE {dol_len}u',
        f'#define DISC_DOL_CRC 0x{crc(dol_off, dol_len):08X}u',
        f'#define DISC_FILE_COUNT {len(files)}u',
        '',
        'static const DiscFile k_disc_files[DISC_FILE_COUNT] = {',
    ]
    lines += [f'    {{ "{p}", {s}u, 0x{c:08X}u }},' for p, o, s, c in files]
    lines += ['};', '', 'static const DiscRelease k_disc_others[] = {']
    lines += [f'    {{ "{i}", {v}, "{name}" }},' for i, v, name in OTHERS]
    lines += ['};', '']
    OUT.write_text('\n'.join(lines), newline='\n')
    print(f'{len(files)} files -> {OUT.relative_to(ROOT)}', file=sys.stderr)


if __name__ == '__main__':
    main()
